// Offline generator. Supply spglib v2.7.0 src/spg_database.c; no full database is redistributed.
import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import assert from 'node:assert/strict';
const source = readFileSync(process.argv[2]);
const sha256 = (data) => createHash('sha256').update(data).digest('hex');
const sourceHash = 'bf1ab8a74e1d275e20ee4145bd409b62b5295e680599d3a112a41d396bde56bd';
assert.equal(sha256(source), sourceHash, 'Source must match pinned spglib v2.7.0');
const text = source.toString();
const encoded = text.split('static int const symmetry_operations[] = {')[1].split('};')[0].replace(/\/\*[\s\S]*?\*\//g, '').split(',').map((s) => s.trim()).filter(Boolean).map(Number);
const index = text.split('static int const symmetry_operation_index[][2] = {')[1].split('};')[0];
const match = index.match(/\{(\d+),\s*(\d+)\},\s*\/\* 517 \*\//);
assert.ok(match);
const [count, start] = match.slice(1).map(Number);
assert.equal(count, 48);
const decoded = encoded.slice(start, start + count).map((value) => {
    const rotation = value % 19683;
    return Array.from({ length: 3 }, (_, row) => Array.from({ length: 3 }, (_, col) => Math.floor(rotation / 3 ** (8 - row * 3 - col)) % 3 - 1));
});
const keys = new Set(decoded.map(JSON.stringify));
assert.equal(keys.size, 48);
// Preserve the prototype's stable operation IDs while verifying each against the source.
const operations = [];
for (const permutation of [[0,1,2],[0,2,1],[1,0,2],[1,2,0],[2,0,1],[2,1,0]]) {
    for (const x of [-1,1]) for (const y of [-1,1]) for (const z of [-1,1]) {
        const linear = permutation.map((col, row) => [0,1,2].map((j) => j === col ? [x,y,z][row] : 0));
        assert.ok(keys.has(JSON.stringify(linear)));
        operations.push({ id: `m-3m-${String(operations.length).padStart(2, '0')}`, linear });
    }
}
const artifact = '// Generated by scripts/generate-m1-registry.mjs; see LICENSE.spglib.\nimport type { PointOperation } from "../symmetry.js";\nexport const CUBIC_OPERATIONS: readonly PointOperation[] = ' + JSON.stringify(operations, null, 2) + ';\n';
const integrity = '// Generated registry integrity metadata.\nexport const REGISTRY_INTEGRITY = ' + JSON.stringify({ sourceSha256: sourceHash, artifactSha256: sha256(artifact), hallNumber: 517, spaceGroupNumber: 221, basis: 'conventional cubic a,b,c; origin at symmetry center', generator: 'scripts/generate-m1-registry.mjs' }, null, 2) + ' as const;\n';
for (const [name, content] of [['cubic-operations.ts', artifact], ['integrity.ts', integrity]]) {
    const path = new URL(`../packages/crystal-core/src/registry/${name}`, import.meta.url);
    if (process.argv.includes('--check')) assert.equal(readFileSync(path, 'utf8'), content, `${name} needs regeneration`);
    else writeFileSync(path, content);
}
console.log(`Verified Hall 517: 48 operations; artifact SHA-256 ${sha256(artifact)}`);
