// Offline normalization of pinned spglib v2.7.0 point-operation subsets.
import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import assert from 'node:assert/strict';
const hash = data => createHash('sha256').update(data).digest('hex');
const source = readFileSync(process.argv[2]);
const sourceSha256 = 'bf1ab8a74e1d275e20ee4145bd409b62b5295e680599d3a112a41d396bde56bd';
assert.equal(hash(source), sourceSha256, 'Expected pinned spglib v2.7.0 source');
const text = source.toString();
const encoded = text.split('static int const symmetry_operations[] = {')[1].split('};')[0]
    .replace(/\/\*[\s\S]*?\*\//g, '').split(',').map(s => s.trim()).filter(Boolean).map(Number);
const index = text.split('static int const symmetry_operation_index[][2] = {')[1].split('};')[0];
const types = text.split('static SpacegroupType const spacegroup_types[] = {')[1].split('};')[0];
// Hall identifiers verified against the pinned source's spacegroup_types table.
const definitions = [
    ['m-3', 'cubic-standard', 'cubic', 501, 205, 24, 'Pa-3; conventional cubic axes'],
    ['4/mmm', 'tetragonal-standard', 'tetragonal', 426, 141, 16, 'I41/amd origin choice 1; conventional tetragonal axes'],
    ['-3m', 'hexagonal-standard', 'trigonal', 460, 167, 12, 'R-3c:H; obverse R-centered hexagonal axes'],
    ['-3m', 'rhombohedral-standard', 'trigonal', 461, 167, 12, 'R-3c:R; primitive rhombohedral axes'],
    ['6/mmm', 'hexagonal-standard', 'hexagonal', 486, 192, 24, 'P6/mcc; conventional hexagonal axes'],
    ['mmm', 'orthorhombic-standard', 'orthorhombic', 294, 62, 8, 'Pbnm (cab setting of No. 62); orthorhombic axes'],
    ['2/m', 'monoclinic-b', 'monoclinic', 90, 15, 4, 'C2/c; unique axis b, cell choice 1'],
    ['-1', 'triclinic-standard', 'triclinic', 2, 2, 2, 'Inversion and identity; valid in primitive or centered triclinic axes'],
];
const identity = [[1,0,0],[0,1,0],[0,0,1]];
const key = JSON.stringify;
const multiply = (a,b) => a.map(row => b[0].map((_,j) => row.reduce((s,v,k) => s+v*b[k][j],0)));
const subsets = definitions.map(([pointGroup,setting,crystalSystem,hallNumber,spaceGroupNumber,n,basis]) => {
    const type = [...types.matchAll(/\{(\d+),[\s\S]*?\}, \/\*\s*(\d+) \*\//g)].find(m => Number(m[2]) === hallNumber);
    assert.equal(Number(type?.[1]), spaceGroupNumber);
    const match = index.match(new RegExp(`\\{(\\d+),\\s*(\\d+)\\},\\s*/\\*\\s*${hallNumber} \\*/`));
    assert.ok(match);
    const [count,start] = match.slice(1).map(Number);
    const matrices = [...new Map(encoded.slice(start,start+count).map(value => {
        const m = Array.from({length:3},(_,i) => Array.from({length:3},(_,j) => Math.floor((value%19683)/3**(8-i*3-j))%3-1));
        return [key(m),m];
    })).values()].sort((a,b) => key(a)<key(b) ? -1 : key(a)>key(b) ? 1 : 0);
    assert.equal(matrices.length,n);
    const keys = new Set(matrices.map(key));
    assert.ok(keys.has(key(identity)));
    for (const a of matrices) {
        assert.ok(matrices.some(b => key(multiply(a,b)) === key(identity)));
        for (const b of matrices) assert.ok(keys.has(key(multiply(a,b))));
    }
    return {id:`point-group:${pointGroup}:${setting}`,pointGroup,setting,crystalSystem,hallNumber,spaceGroupNumber,basis,
        operations:matrices.map((linear,i) => ({id:`hall-${hallNumber}-point-${String(i).padStart(2,'0')}`,linear}))};
});
const artifact = '// Generated by scripts/generate-m5-registry.mjs; see LICENSE.spglib.\n'
    + 'export const M5_SUBSETS = ' + JSON.stringify(subsets,null,2) + ' as const;\n';
const integrity = '// Generated by scripts/generate-m5-registry.mjs.\nexport const M5_INTEGRITY = '
    + JSON.stringify({sourceSha256,artifactSha256:hash(artifact),generator:'scripts/generate-m5-registry.mjs'},null,2) + ' as const;\n';
for (const [name,content] of [['m5-operations.ts',artifact],['m5-integrity.ts',integrity]]) {
    const path = new URL(`../packages/crystal-core/src/registry/${name}`,import.meta.url);
    if (process.argv.includes('--check')) assert.equal(readFileSync(path,'utf8'),content);
    else writeFileSync(path,content);
}
console.log(`Verified ${subsets.length} M5 subsets: ${hash(artifact)}`);
