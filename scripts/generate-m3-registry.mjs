// Offline generator for the trigonal point-group 32 registry subset.
// Supply spglib v2.7.0 src/spg_database.c (same pinned source as M1).
import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import assert from 'node:assert/strict';

const source = readFileSync(process.argv[2]);
const sha256 = (data) => createHash('sha256').update(data).digest('hex');
const sourceHash = 'bf1ab8a74e1d275e20ee4145bd409b62b5295e680599d3a112a41d396bde56bd';
assert.equal(sha256(source), sourceHash, 'Source must match pinned spglib v2.7.0');

const text = source.toString();
const encoded = text.split('static int const symmetry_operations[] = {')[1]
    .split('};')[0]
    .replace(/\/\*[\s\S]*?\*\//g, '')
    .split(',')
    .map((s) => s.trim())
    .filter(Boolean)
    .map(Number);

const index = text.split('static int const symmetry_operation_index[][2] = {')[1].split('};')[0];

// Hall 441 = P 3_1 2 1 (space group 152, right-handed quartz).
const match = index.match(/\{(\d+),\s*(\d+)\},\s*\/\* 441 \*\//);
assert.ok(match, 'Hall 441 entry not found');
const [count, start] = match.slice(1).map(Number);
assert.equal(count, 6, 'P3_121 should have 6 general positions');

// Decode base-3 rotation matrices; discard translations (point operations only).
const decoded = encoded.slice(start, start + count).map((value) => {
    const rotation = value % 19683; // 3^9
    return Array.from({ length: 3 }, (_, row) =>
        Array.from({ length: 3 }, (_, col) =>
            Math.floor(rotation / 3 ** (8 - row * 3 - col)) % 3 - 1
        )
    );
});

// Deduplicate the linear matrices to get the point-group operations.
const seen = new Set();
const pointOps = [];
for (const matrix of decoded) {
    const key = JSON.stringify(matrix);
    if (!seen.has(key)) {
        seen.add(key);
        pointOps.push(matrix);
    }
}

// Order the operations deterministically: identity, 3-fold+, 3-fold-, then 2-folds.
const identity = [[1,0,0],[0,1,0],[0,0,1]];
const c3Plus = [[0,-1,0],[1,-1,0],[0,0,1]];
const c3Minus = [[-1,1,0],[-1,0,0],[0,0,1]];

function matEqual(a, b) {
    return a.every((row, i) => row.every((v, j) => v === b[i][j]));
}

// Verify all 6 point operations are present.
assert.ok(pointOps.some((m) => matEqual(m, identity)), 'Missing identity');
assert.ok(pointOps.some((m) => matEqual(m, c3Plus)), 'Missing C3+');
assert.ok(pointOps.some((m) => matEqual(m, c3Minus)), 'Missing C3-');
assert.equal(pointOps.length, 6, 'Point group 32 should have 6 operations');

// Order: E, C3+, C3-, then the three 2-fold axes (sorted by their matrix string).
const ordered = [identity, c3Plus, c3Minus];
const twofolds = pointOps.filter((m) => !ordered.some((o) => matEqual(o, m)));
twofolds.sort((a, b) => JSON.stringify(a).localeCompare(JSON.stringify(b)));
ordered.push(...twofolds);

const operations = ordered.map((linear, i) => ({
    id: `32-${String(i).padStart(2, '0')}`,
    linear,
}));

// Verify group closure.
function multiply(a, b) {
    return a.map((row, i) =>
        b[0].map((_, j) => row.reduce((sum, x, k) => sum + x * b[k][j], 0))
    );
}
function isIdentity(m) { return matEqual(m, identity); }
const keys = new Set(ordered.map((m) => JSON.stringify(m)));
for (const a of ordered) {
    assert.ok(ordered.some((b) => matEqual(multiply(a, b), identity)), `Missing inverse for ${JSON.stringify(a)}`);
    for (const b of ordered) {
        const prod = multiply(a, b);
        assert.ok(keys.has(JSON.stringify(prod)), `Not closed: ${JSON.stringify(a)} * ${JSON.stringify(b)} = ${JSON.stringify(prod)}`);
    }
}

const artifact = `// Generated by scripts/generate-m3-registry.mjs; see LICENSE.spglib.
import type { PointOperation } from "../symmetry.js";
export const TRIGONAL_32_OPERATIONS: readonly PointOperation[] = ${JSON.stringify(operations, null, 2)};
`;

const artifactHash = sha256(artifact);
const integrity = `// Generated registry integrity metadata.
export const TRIGONAL_32_INTEGRITY = ${JSON.stringify({
    sourceSha256: sourceHash,
    artifactSha256: artifactHash,
    hallNumber: 441,
    spaceGroupNumber: 152,
    basis: 'hexagonal a1,a2,c; 3-fold along c; 2-fold along a-axes',
    generator: 'scripts/generate-m3-registry.mjs',
}, null, 2)} as const;
`;

const registryDir = new URL('../packages/crystal-core/src/registry/', import.meta.url);
for (const [name, content] of [['trigonal-operations.ts', artifact], ['trigonal-integrity.ts', integrity]]) {
    const path = new URL(name, registryDir);
    if (process.argv.includes('--check')) {
        assert.equal(readFileSync(path, 'utf8'), content, `${name} needs regeneration`);
    } else {
        writeFileSync(path, content);
    }
}

console.log(`Verified Hall 441 (P3_121, sg 152): ${operations.length} point operations (point group 32); artifact SHA-256 ${artifactHash}`);
